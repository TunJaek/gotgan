<?php

namespace App\Support;

/**
 * 시·도 이름은 법정동 코드 앞 2자리로 서버가 정한다. 브라우저가 보낸 글자는 믿지 않는다(2026-09-29).
 * 주소 검색 저장(PicksRegion)과 장터 목록의 지역 선택지가 같이 쓴다.
 *
 * 시·도가 새로 생기거나 코드가 바뀌면 여기에 한 줄 더한다.
 * 없는 코드가 들어오면 막지 않고 카카오가 준 이름을 쓴다(개편 직후에도 등록이 막히지 않게).
 */
class Sido
{
    public const NAMES = [
        '11' => '서울', '12' => '전남광주', '26' => '부산', '27' => '대구', '28' => '인천',
        '30' => '대전', '31' => '울산', '36' => '세종', '41' => '경기', '43' => '충북',
        '44' => '충남', '47' => '경북', '48' => '경남', '50' => '제주', '51' => '강원', '52' => '전북',
        // 개편 전 코드. 옛 매물이나 카카오가 아직 옛 코드를 줄 때
        '29' => '광주', '42' => '강원', '45' => '전북', '46' => '전남',
    ];

    public static function name(string $code): ?string
    {
        return self::NAMES[substr($code, 0, 2)] ?? null;
    }
}
